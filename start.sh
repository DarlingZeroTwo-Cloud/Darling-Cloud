clear
mkdir -p 下载
echo -e "\033[1;32m==========================================================\033[0m"
echo -e "\033[1;36m          ██╗  ██╗ █████╗ ██████╗ ██╗     ███████╗\033[0m"
echo -e "\033[1;36m          ██║  ██║██╔══██╗██╔══██╗██║     ██╔════╝\033[0m"
echo -e "\033[1;36m          ███████║███████║██████╔╝██║     █████╗  \033[0m"
echo -e "\033[1;36m          ██╔══██║██╔══██║██╔══██╗██║     ██╔══╝  \033[0m"
echo -e "\033[1;36m          ██║  ██║██║  ██║██║  ██║███████╗███████╗\033[0m"
echo -e "\033[1;36m          ╚═╝  ╚═╝╚═╝  ╚═╝╚═╝  ╚═╝╚══════╝╚══════╝\033[0m"
echo -e "\033[1;35m     Darling Zero Two 极速测速｜2秒测1-256线程\033[0m"
echo -e "\033[1;32m==========================================================\033[0m"
echo ""
echo "规则：2秒极速测试1~256线程 → 取最高稳定线程 → 全速下载"
echo "实时显示：总进度｜总速度MB/s｜各线程速度"
echo ""
read -p "请粘贴下载链接：" link
echo ""

# 安装 aria2（兼容 Linux + macOS）
if ! command -v aria2c &> /dev/null; then
    echo "正在安装 aria2 高速下载引擎..."
    if [[ "$(uname)" == "Darwin" ]]; then
        brew install aria2
    else
        sudo apt update && sudo apt install aria2 -y
    fi
fi

stable=1
echo -e "\033[1;33m==============================================\033[0m"
echo -e "\033[1;33m【极速测速中 2秒内完成 1~256线程】\033[0m"
echo -e "\033[1;33m==============================================\033[0m"
echo ""

# 测速
for ((t=1;t<=256;t++)); do
    aria2c -x$t -s$t -k1M -d "下载" --timeout=1 --max-tries=1 --dry-run "$link" >/dev/null 2>&1
    ret=$?
    if [ $ret -eq 28 ]; then
        break
    fi
    stable=$t
done

echo ""
echo -e "\033[1;33m==============================================\033[0m"
echo -e "\033[1;33m测速完成｜最高稳定线程：$stable\033[0m"
echo -e "\033[1;33m开始全速下载｜实时显示进度+速度+各线程速度\033[0m"
echo -e "\033[1;33m==============================================\033[0m"
echo ""

aria2c -x$stable -s$stable -k1M -d "下载" --timeout=8 "$link"
final_ret=$?

echo ""
if [ $final_ret -eq 0 ]; then
    echo -e "\033[1;32m==============================================\033[0m"
    echo -e "\033[1;32m✅ 下载成功！文件保存在【下载】文件夹\033[0m"
    echo -e "\033[1;32m==============================================\033[0m"
else
    echo -e "\033[1;31m❌ 下载失败，错误码：$final_ret\033[0m"
fi